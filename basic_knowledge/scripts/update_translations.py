CHINESE_RE = re.compile(r"[\u4e00-\u9fff]")

missing: set[str] = set()

def translate_value(value):
    if isinstance(value, str) and CHINESE_RE.search(value):
        if value not in TRANSLATIONS:
            missing.add(value)
            return value
        return TRANSLATIONS[value]
    if isinstance(value, list):
        return [translate_value(v) for v in value]
    if isinstance(value, dict):
        return {k: translate_value(v) for k, v in value.items()}
    return value

def translate_en_fields(node):
    if isinstance(node, dict):
        new = {}
        for k, v in node.items():
            if k == "en":
                new[k] = translate_value(v)
            else:
                new[k] = translate_en_fields(v)
        return new
    if isinstance(node, list):
        return [translate_en_fields(item) for item in node]
    return node

if len(sys.argv) < 2:
    print("Usage: python basic_knowledge/scripts/update_translations.py <file> [<file> ...]")
    sys.exit(1)

for arg in sys.argv[1:]:
    path = Path(arg)
    data = json.loads(path.read_text(encoding="utf-8"))
    result = translate_en_fields(data)
    if missing:
        print(f"Missing translations for {path}:")
        for item in sorted(missing):
            print("  ", item)
        missing.clear()
        continue
    path.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Updated {path}")
